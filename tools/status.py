#!/usr/bin/env python3
"""Generate the README's "Start here" table from the recipes and release files.

Writes the table between the status markers in README.md. With --check, changes nothing and exits 1 if the README is
out of date, so CI can require that it was regenerated.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import sys

README = Path('README.md')
BEGIN, END = '<!-- status:begin (generated by tools/status.py) -->', '<!-- status:end -->'


def short(repo_at):
    repo, _, rev = repo_at.partition('@')
    return f'[`{repo.split("/")[-1]}@{rev[:7]}`](https://github.com/{repo}/tree/{rev})'


def row(recipe_path):
    recipe = json.loads(recipe_path.read_text())
    lane, engine, kit = recipe['lane'], recipe['engine'], recipe.get('kit')
    if kit:
        builds = (f"{recipe['model']}: {short(kit['repository'] + '@' + kit['revision'])} on TensorFold "
                  f"`{engine['upstream'].rpartition('@')[2][:8]}`")
    else:
        builds = f"{recipe['model']}: upstream {short(engine['upstream'])}"
    carries = recipe.get('carries', [])
    counts = Counter(c.get('upstream') for c in carries)  # first appearance order: the recipe's, oldest first
    raised = Counter(c['issue'] for c in carries if c.get('issue') and not c.get('upstream'))
    pending = ''.join(f' ({n} raised as {issue})' for issue, n in raised.items())
    parts = [f'{n} from {upstream}' if upstream else f'{n} not upstream yet{pending}' for upstream, n in counts.items()]
    ours = (f"[{len(carries)} commit{'s' if len(carries) > 1 else ''}](recipes/{lane}/recipe.json): {', '.join(parts)}"
            if carries else 'none')
    releases = sorted(recipe_path.parent.glob('releases/*.json'),
                      key=lambda p: [int(x) for x in p.stem.removeprefix(f'{lane}-').split('.')])
    if releases:
        latest = json.loads(releases[-1].read_text())
        release = f"[`{latest['release']}`](recipes/{lane}/releases/{releases[-1].name})"
        status = latest['qualification']['status']
        if latest['engine']['commit'] != engine['commit']:
            status += '; the recipe has moved on since'
    else:
        release, status = 'none yet', 'n/a'
    engine_link = f"[`{engine['commit'][:8]}`](https://github.com/{engine['repository']}/commit/{engine['commit']})"
    return f'| [`{lane}`](recipes/{lane}/) | {builds} | {ours} | {engine_link} | {release} | {status} |'


def table():
    rows = [row(p) for p in sorted(Path('recipes').glob('*/recipe.json'))]
    return '\n'.join(['| Lane | Builds | Our engine changes | Engine commit | Latest release | Qualification |',
                      '| --- | --- | --- | --- | --- | --- |', *rows])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = README.read_text()
    head, _, rest = text.partition(BEGIN)
    _, _, tail = rest.partition(END)
    if not rest or END not in rest:
        sys.exit(f'README.md needs the {BEGIN} and {END} markers')
    updated = f'{head}{BEGIN}\n{table()}\n{END}{tail}'
    if args.check:
        if updated != text:
            sys.exit('README.md status is out of date: run tools/status.py')
        print('README.md status is current')
    else:
        README.write_text(updated)
        print('README.md status regenerated')


if __name__ == '__main__':
    main()
